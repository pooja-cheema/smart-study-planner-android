package edu.niu.android.smartstudyplanner.data.entities;

import androidx.room.Entity;
import androidx.room.ForeignKey;
import androidx.room.Index;
import androidx.room.PrimaryKey;

@Entity(
        tableName = "tasks",
        foreignKeys = @ForeignKey(
                entity = Course.class,
                parentColumns = "id",
                childColumns = "courseId",
                onDelete = ForeignKey.CASCADE
        ),
        indices = {@Index("courseId")}
)
public class Task {

    // Task type constants stored in the type column.
    public static final int TYPE_ASSIGNMENT = 0;
    public static final int TYPE_EXAM = 1;
    public static final int TYPE_QUIZ = 2;
    public static final int TYPE_PROJECT = 3;
    public static final int TYPE_OTHER = 4;

    // Priority constants stored in the priority column.
    public static final int PRIORITY_LOW = 0;
    public static final int PRIORITY_MEDIUM = 1;
    public static final int PRIORITY_HIGH = 2;

    // Auto generated primary key assigned by Room on insert.
    @PrimaryKey(autoGenerate = true)
    private long id;

    // ID of the course this task belongs to.
    private long courseId;

    // Short task title shown in the list and notification.
    private String title;

    // Longer description shown on the task detail/edit screen.
    private String description;

    // One of the TYPE_ constants above.
    private int type;

    // One of the PRIORITY_ constants above.
    private int priority;

    // Timestamp (millis) when the task is due.
    private long dueDate;

    // True once the user marks the task complete.
    private boolean completed;

    // Timestamp (millis) when the task was marked complete; 0 if not yet.
    private long completedAt;

    // Timestamp (millis) when the task was added.
    private long createdAt;

    // True if a deadline reminder alarm is currently scheduled for this task.
    private boolean notificationSet;

    /**
     * Builds a new task. New tasks start as incomplete with no notification
     * scheduled; the id is auto generated by Room on insert.
     */
    public Task(long courseId, String title, String description, int type,
                int priority, long dueDate, long createdAt) {
        this.courseId = courseId;
        this.title = title;
        this.description = description;
        this.type = type;
        this.priority = priority;
        this.dueDate = dueDate;
        this.completed = false;
        this.completedAt = 0;
        this.createdAt = createdAt;
        this.notificationSet = false;
    }

    // Standard getters and setters used by Room and the UI.

    public long getId() { return id; }
    public void setId(long id) { this.id = id; }

    public long getCourseId() { return courseId; }
    public void setCourseId(long courseId) { this.courseId = courseId; }

    public String getTitle() { return title; }
    public void setTitle(String title) { this.title = title; }

    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }

    public int getType() { return type; }
    public void setType(int type) { this.type = type; }

    public int getPriority() { return priority; }
    public void setPriority(int priority) { this.priority = priority; }

    public long getDueDate() { return dueDate; }
    public void setDueDate(long dueDate) { this.dueDate = dueDate; }

    public boolean isCompleted() { return completed; }
    public void setCompleted(boolean completed) { this.completed = completed; }

    public long getCompletedAt() { return completedAt; }
    public void setCompletedAt(long completedAt) { this.completedAt = completedAt; }

    public long getCreatedAt() { return createdAt; }
    public void setCreatedAt(long createdAt) { this.createdAt = createdAt; }

    public boolean isNotificationSet() { return notificationSet; }
    public void setNotificationSet(boolean notificationSet) { this.notificationSet = notificationSet; }

    /**
     * Returns the human readable label for the task's type, used by adapters
     * and detail screens to render the type chip.
     */
    public String getTypeLabel() {
        switch (type) {
            case TYPE_ASSIGNMENT: return "Assignment";
            case TYPE_EXAM: return "Exam";
            case TYPE_QUIZ: return "Quiz";
            case TYPE_PROJECT: return "Project";
            default: return "Other";
        }
    }

    /**
     * Returns the human readable label for the task's priority, used by
     * adapters to render the priority badge.
     */
    public String getPriorityLabel() {
        switch (priority) {
            case PRIORITY_LOW: return "Low";
            case PRIORITY_HIGH: return "High";
            default: return "Medium";
        }
    }
}