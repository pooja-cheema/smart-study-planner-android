package edu.niu.android.smartstudyplanner.data.entities;

import androidx.room.Entity;
import androidx.room.ForeignKey;
import androidx.room.Index;
import androidx.room.PrimaryKey;

@Entity(
        tableName = "study_sessions",
        foreignKeys = @ForeignKey(
                entity = Course.class,
                parentColumns = "id",
                childColumns = "courseId",
                onDelete = ForeignKey.SET_NULL
        ),
        indices = {@Index("courseId")}
)
public class StudySession {

    // Session type constants stored in the sessionType column.
    public static final int SESSION_TYPE_POMODORO = 0;
    public static final int SESSION_TYPE_FREE = 1;

    // Auto generated primary key assigned by Room on insert.
    @PrimaryKey(autoGenerate = true)
    private long id;

    // ID of the course this session is tagged with, or null for general study.
    private Long courseId;

    // Optional free text note the user can add to the session.
    private String notes;

    // Timestamps (millis) for when the session started and ended.
    private long startTime;
    private long endTime;

    // Total focus time recorded during the session, in seconds.
    private long durationSeconds;

    // SESSION_TYPE_POMODORO or SESSION_TYPE_FREE.
    private int sessionType;

    // How many full Pomodoro work intervals were completed in the session.
    private int pomodoroCount;

    // True if the user explicitly saved the session (vs being abandoned).
    private boolean completed;

    /**
     * Builds a new study session. The id is auto generated by Room on insert,
     * so callers don't pass it in.
     */
    public StudySession(Long courseId, String notes, long startTime, long endTime,
                        long durationSeconds, int sessionType, int pomodoroCount, boolean completed) {
        this.courseId = courseId;
        this.notes = notes;
        this.startTime = startTime;
        this.endTime = endTime;
        this.durationSeconds = durationSeconds;
        this.sessionType = sessionType;
        this.pomodoroCount = pomodoroCount;
        this.completed = completed;
    }

    // Standard getters and setters used by Room and the UI.

    public long getId() { return id; }
    public void setId(long id) { this.id = id; }

    public Long getCourseId() { return courseId; }
    public void setCourseId(Long courseId) { this.courseId = courseId; }

    public String getNotes() { return notes; }
    public void setNotes(String notes) { this.notes = notes; }

    public long getStartTime() { return startTime; }
    public void setStartTime(long startTime) { this.startTime = startTime; }

    public long getEndTime() { return endTime; }
    public void setEndTime(long endTime) { this.endTime = endTime; }

    public long getDurationSeconds() { return durationSeconds; }
    public void setDurationSeconds(long durationSeconds) { this.durationSeconds = durationSeconds; }

    public int getSessionType() { return sessionType; }
    public void setSessionType(int sessionType) { this.sessionType = sessionType; }

    public int getPomodoroCount() { return pomodoroCount; }
    public void setPomodoroCount(int pomodoroCount) { this.pomodoroCount = pomodoroCount; }

    public boolean isCompleted() { return completed; }
    public void setCompleted(boolean completed) { this.completed = completed; }

    /**
     * Returns the duration as a short readable string like "1h 30m" or "45m".
     * Used in the recent sessions list on the Stats and Timer screens.
     */
    public String getFormattedDuration() {
        long minutes = durationSeconds / 60;
        long hours = minutes / 60;
        long remainingMinutes = minutes % 60;
        if (hours > 0) {
            return hours + "h " + remainingMinutes + "m";
        } else {
            return remainingMinutes + "m";
        }
    }
}